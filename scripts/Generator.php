<?php

declare(strict_types=1);

namespace Hash\Dev;

use RuntimeException;

/**
 * Generates the enums, models, services and operation table from spec/openapi.json.
 *
 * Run `composer generate` (or `php scripts/generate.php`). The output is committed;
 * tests/GeneratedCodeTest fails when it drifts from the spec.
 */
final class Generator
{
    public const MARKER = 'Generated by scripts/generate.php';

    /** operationId => [service property, method name]. A spec operation missing here fails generation. */
    public const OPERATION_NAMES = [
        'listInvoices' => ['invoices', 'list'],
        'createInvoice' => ['invoices', 'create'],
        'retrieveInvoice' => ['invoices', 'retrieve'],
        'acceptPayment' => ['invoices', 'accept'],
        'cancelInvoice' => ['invoices', 'cancel'],
        'creditWrongNetwork' => ['invoices', 'creditWrongNetwork'],
        'listBalances' => ['balances', 'retrieve'],
        'listWebhookEndpoints' => ['webhookEndpoints', 'list'],
        'createWebhookEndpoint' => ['webhookEndpoints', 'create'],
        'retrieveWebhookEndpoint' => ['webhookEndpoints', 'retrieve'],
        'updateWebhookEndpoint' => ['webhookEndpoints', 'update'],
        'enableWebhookEndpoint' => ['webhookEndpoints', 'enable'],
        'testWebhookEndpoint' => ['webhookEndpoints', 'test'],
        'listWebhookDeliveries' => ['webhookDeliveries', 'list'],
        'resendWebhookDelivery' => ['webhookDeliveries', 'resend'],
        'listWebhookSourceIps' => ['meta', 'webhookIps'],
    ];

    public const SERVICE_CLASSES = [
        'invoices' => 'InvoiceService',
        'balances' => 'BalanceService',
        'webhookEndpoints' => 'WebhookEndpointService',
        'webhookDeliveries' => 'WebhookDeliveryService',
        'meta' => 'MetaService',
    ];

    /** String enums of the spec that get a class of constants. */
    public const ENUMS = ['Asset', 'Chain', 'Mode', 'Network', 'InvoiceStatus', 'WebhookEventType', 'ErrorCode'];

    /** Schemas that are not response objects: requests, list envelopes and error bodies. */
    private const NOT_MODELS = ['/Request$/', '/List$/', '/^Error$/', '/^ValidationError$/', '/Event$/'];

    /** Inline objects inside webhook event payloads, and the model each becomes. */
    public const EVENT_DATA_MODELS = [
        'WalletDepositConfirmedEvent' => ['wallet' => 'Wallet', 'details' => 'WalletDepositDetails'],
        'WebhookTestEvent' => ['test' => 'WebhookTest'],
    ];

    /** @var array<string, mixed> */
    private array $spec;

    /** @var array<string, string> */
    private array $files = [];

    /** @param array<string, mixed> $spec */
    public function __construct(array $spec)
    {
        $this->spec = $spec;
    }

    /** @return array<string, mixed> */
    public static function loadSpec(string $root): array
    {
        $json = file_get_contents($root . '/spec/openapi.json');
        if ($json === false) {
            throw new RuntimeException('Cannot read spec/openapi.json');
        }
        /** @var array<string, mixed> $spec */
        $spec = json_decode($json, true, 512, JSON_THROW_ON_ERROR);

        return $spec;
    }

    /** @return array<string, string> path relative to the package root => content */
    public function generate(): array
    {
        $this->files = [];
        foreach (self::ENUMS as $name) {
            $this->enumClass($name, $this->schemas()[$name]['enum']);
        }
        $this->enumClass('EventType', array_map('strval', array_keys($this->spec['webhooks'])), 'Every event type Hash sends, including `webhook.test` (which cannot be subscribed to).');

        foreach ($this->schemas() as $name => $schema) {
            if (($schema['type'] ?? null) !== 'object' || !isset($schema['properties']) || $this->matchesAny($name, self::NOT_MODELS)) {
                continue;
            }
            $this->modelClass($name, $schema);
        }
        foreach ($this->schemas() as $name => $schema) {
            if (!str_ends_with($name, 'Event')) {
                continue;
            }
            foreach ($schema['properties']['data']['properties'] as $prop => $sub) {
                if (isset($sub['$ref']) || !isset($sub['properties'])) {
                    continue;
                }
                $model = self::EVENT_DATA_MODELS[$name][$prop] ?? null;
                if ($model === null) {
                    throw new RuntimeException("$name.data.$prop is an inline object without a model name: add it to EVENT_DATA_MODELS.");
                }
                $this->modelClass($model, $sub);
            }
        }

        $ops = $this->operations();
        $this->operationsClass($ops);
        $this->serviceClasses($ops);
        ksort($this->files);

        return $this->files;
    }

    // ---------------------------------------------------------------- helpers

    /** @return array<string, array<string, mixed>> */
    private function schemas(): array
    {
        return $this->spec['components']['schemas'];
    }

    /** @param list<string> $patterns */
    private function matchesAny(string $name, array $patterns): bool
    {
        foreach ($patterns as $p) {
            if (preg_match($p, $name) === 1) {
                return true;
            }
        }

        return false;
    }

    private function header(): string
    {
        return "<?php\n\ndeclare(strict_types=1);\n\n// " . self::MARKER . ' from spec/openapi.json (Hash API ' . $this->spec['info']['version'] . "). Do not edit.\n// Run `composer generate` after updating the spec.\n\n";
    }

    private static function refName(string $ref): string
    {
        $parts = explode('/', $ref);

        return end($parts);
    }

    /**
     * @param array<string, mixed> $schema
     *
     * @return array<string, mixed>
     */
    private function resolve(array $schema): array
    {
        while (isset($schema['$ref'])) {
            $schema = $this->schemas()[self::refName($schema['$ref'])];
        }

        return $schema;
    }

    private static function pascal(string $s): string
    {
        return str_replace(' ', '', ucwords(str_replace(['_', '-', '.', '[', ']'], ' ', $s)));
    }

    private static function constName(string $value): string
    {
        return strtoupper((string) preg_replace('/[^A-Za-z0-9]+/', '_', $value));
    }

    /** @param list<string> $extra */
    private static function doc(?string $text, string $indent, array $extra = []): string
    {
        $lines = [];
        if ($text !== null && $text !== '') {
            foreach (explode("\n", str_replace('*/', '*\\/', $text)) as $l) {
                $lines[] = $l;
            }
        }
        if ($extra !== [] && $lines !== []) {
            $lines[] = '';
        }
        foreach ($extra as $e) {
            $lines[] = $e;
        }
        if ($lines === []) {
            return '';
        }
        $out = "$indent/**\n";
        foreach ($lines as $l) {
            $out .= $indent . ' *' . ($l === '' ? '' : ' ' . $l) . "\n";
        }

        return $out . "$indent */\n";
    }

    // ---------------------------------------------------------------- enums

    /** @param list<string> $values */
    private function enumClass(string $name, array $values, ?string $description = null): void
    {
        $description ??= $this->schemas()[$name]['description'] ?? null;
        $out = $this->header() . "namespace Hash\\Enum;\n\n";
        $out .= self::doc($description, '', ['Constants, not a PHP enum: Hash may add values, so compare strings and keep a default branch.']);
        $out .= "final class $name\n{\n";
        foreach ($values as $v) {
            $out .= '    public const ' . self::constName($v) . ' = ' . var_export($v, true) . ";\n";
        }
        $out .= "\n    /** Every value the spec lists. */\n    public const ALL = [\n";
        foreach ($values as $v) {
            $out .= '        self::' . self::constName($v) . ",\n";
        }
        $out .= "    ];\n\n    private function __construct()\n    {\n    }\n}\n";
        $this->files["src/Enum/$name.php"] = $out;
    }

    // ---------------------------------------------------------------- models

    /**
     * Describes how a property is typed and read.
     *
     * @param array<string, mixed> $schema
     *
     * @return array{native: string, doc: string|null, read: string, nullable: bool}
     */
    private function propType(string $owner, string $prop, array $schema, bool $required): array
    {
        $nullable = !$required;
        $s = $schema;
        if (isset($s['oneOf'])) {
            $nonNull = array_values(array_filter($s['oneOf'], static fn (array $o): bool => ($o['type'] ?? null) !== 'null'));
            if (count($nonNull) !== count($s['oneOf'])) {
                $nullable = true;
            }
            if (count($nonNull) !== 1) {
                throw new RuntimeException("$owner.$prop: unsupported oneOf");
            }
            $s = $nonNull[0] + array_diff_key($s, ['oneOf' => true]);
        }

        $modelRef = null;
        if (isset($s['$ref'])) {
            $refName = self::refName($s['$ref']);
            $target = $this->resolve($s);
            if (($target['type'] ?? null) === 'object' && isset($target['properties'])) {
                $modelRef = $refName;
            }
            $s = $target + ['description' => null];
        }

        $types = is_array($s['type'] ?? null) ? $s['type'] : (isset($s['type']) ? [$s['type']] : []);
        if (isset($s['const'])) {
            $types = [is_bool($s['const']) ? 'boolean' : 'string'];
        }
        if (in_array('null', $types, true)) {
            $nullable = true;
            $types = array_values(array_diff($types, ['null']));
        }
        if ($types === [] && $modelRef === null) {
            throw new RuntimeException("$owner.$prop: no type");
        }
        $q = $nullable ? '?' : '';
        $nul = $nullable ? 'Nullable' : '';
        $key = var_export($prop, true);

        if ($modelRef !== null) {
            return ['native' => $q . $modelRef, 'doc' => null, 'read' => "self::{$this->lc($nul)}model(\$data, $key, $modelRef::class)", 'nullable' => $nullable];
        }
        $type = $types[0];
        if (count($types) > 1) {
            if ($types === ['string', 'number', 'boolean']) {
                return ['native' => $q . 'string|int|float|bool', 'doc' => null, 'read' => "self::{$this->lc($nul)}scalar(\$data, $key)", 'nullable' => $nullable];
            }
            throw new RuntimeException("$owner.$prop: unsupported type union " . implode('|', $types));
        }

        switch ($type) {
            case 'string':
                return ['native' => $q . 'string', 'doc' => null, 'read' => "self::{$this->lc($nul)}string(\$data, $key)", 'nullable' => $nullable];
            case 'integer':
                return ['native' => $q . 'int', 'doc' => null, 'read' => "self::{$this->lc($nul)}int(\$data, $key)", 'nullable' => $nullable];
            case 'number':
                return ['native' => $q . 'float', 'doc' => null, 'read' => "self::{$this->lc($nul)}float(\$data, $key)", 'nullable' => $nullable];
            case 'boolean':
                return ['native' => $q . 'bool', 'doc' => null, 'read' => "self::{$this->lc($nul)}bool(\$data, $key)", 'nullable' => $nullable];
            case 'array':
                $items = $s['items'] ?? [];
                $itemSchema = $this->resolve($items);
                if (isset($items['$ref']) && ($itemSchema['type'] ?? null) === 'object') {
                    $cls = self::refName($items['$ref']);

                    return ['native' => $q . 'array', 'doc' => "list<$cls>" . ($nullable ? '|null' : ''), 'read' => "self::{$this->lc($nul)}modelList(\$data, $key, $cls::class)", 'nullable' => $nullable];
                }
                if (($itemSchema['type'] ?? null) === 'string') {
                    return ['native' => $q . 'array', 'doc' => 'list<string>' . ($nullable ? '|null' : ''), 'read' => "self::{$this->lc($nul)}stringList(\$data, $key)", 'nullable' => $nullable];
                }
                throw new RuntimeException("$owner.$prop: unsupported array items");
            case 'object':
                if (isset($s['properties'])) {
                    $nested = $owner . self::pascal($prop);
                    $this->modelClass($nested, $s);

                    return ['native' => $q . $nested, 'doc' => null, 'read' => "self::{$this->lc($nul)}model(\$data, $key, $nested::class)", 'nullable' => $nullable];
                }

                return ['native' => $q . 'array', 'doc' => 'array<string, mixed>' . ($nullable ? '|null' : ''), 'read' => "self::{$this->lc($nul)}map(\$data, $key)", 'nullable' => $nullable];
        }
        throw new RuntimeException("$owner.$prop: unsupported type $type");
    }

    /** `Nullable` becomes the `nullable` prefix of a helper name; nothing stays nothing. */
    private function lc(string $nul): string
    {
        return $nul === '' ? '' : 'nullable';
    }

    /** @param array<string, mixed> $schema */
    private function modelClass(string $name, array $schema): void
    {
        $path = "src/Model/$name.php";
        if (isset($this->files[$path])) {
            return;
        }
        $this->files[$path] = ''; // reserve, for nested models
        $required = $schema['required'] ?? [];
        $props = '';
        $reads = '';
        foreach ($schema['properties'] as $prop => $p) {
            $t = $this->propType($name, $prop, $p, in_array($prop, $required, true));
            $extra = [];
            if ($t['doc'] !== null) {
                $extra[] = '@var ' . $t['doc'];
            }
            if (!empty($p['deprecated'])) {
                $extra[] = '@deprecated';
            }
            $props .= self::doc($p['description'] ?? null, '    ', $extra);
            $props .= "    public readonly {$t['native']} \$$prop;\n\n";
            // A helper name is camelCase: nullableString, nullableModel ...
            $read = preg_replace_callback('/self::nullable([a-z])/', static fn (array $m): string => 'self::nullable' . strtoupper($m[1]), $t['read']);
            $reads .= "        \$this->$prop = $read;\n";
        }

        $out = $this->header() . "namespace Hash\\Model;\n\n";
        $out .= self::doc($schema['description'] ?? null, '', ['Fields Hash adds later are kept in toArray(). Read only.']);
        $out .= "final class $name extends AbstractModel\n{\n";
        $out .= $props;
        $out .= "    /** @param array<string, mixed> \$data */\n";
        $out .= "    protected function __construct(array \$data)\n    {\n";
        $out .= "        parent::__construct(\$data);\n";
        $out .= $reads;
        $out .= "    }\n\n";
        $out .= "    /** @param array<string, mixed> \$data */\n";
        $out .= "    public static function fromArray(array \$data): static\n    {\n";
        $out .= "        return new static(\$data);\n    }\n}\n";
        $this->files[$path] = $out;
    }

    // ---------------------------------------------------------------- operations

    /** @return list<array<string, mixed>> */
    private function operations(): array
    {
        $ops = [];
        foreach ($this->spec['paths'] as $path => $item) {
            foreach (['get', 'post', 'patch', 'put', 'delete'] as $method) {
                if (!isset($item[$method])) {
                    continue;
                }
                $op = $item[$method];
                $id = $op['operationId'];
                if (!isset(self::OPERATION_NAMES[$id])) {
                    throw new RuntimeException("Operation $id has no SDK name: add it to OPERATION_NAMES.");
                }
                $params = [];
                foreach (array_merge($item['parameters'] ?? [], $op['parameters'] ?? []) as $p) {
                    $params[] = isset($p['$ref']) ? $this->spec['components']['parameters'][self::refName($p['$ref'])] : $p;
                }
                $code = null;
                foreach (array_keys($op['responses']) as $c) {
                    if (preg_match('/^2\d\d$/', (string) $c) === 1) {
                        $code = (int) $c;
                        break;
                    }
                }
                if ($code === null) {
                    throw new RuntimeException("No 2xx response for $id");
                }
                $responseSchema = $op['responses'][(string) $code]['content']['application/json']['schema'];
                $resolved = $this->resolve($responseSchema);
                $listItem = null;
                if (($resolved['properties']['object']['enum'] ?? null) === ['list'] && isset($resolved['properties']['has_more'], $resolved['properties']['next_cursor'])) {
                    $listItem = self::refName($resolved['properties']['data']['items']['$ref']);
                }
                $idempotency = false;
                foreach ($params as $p) {
                    if ($p['in'] === 'header' && $p['name'] === 'Idempotency-Key' && ($p['required'] ?? false)) {
                        $idempotency = true;
                    }
                }
                $ops[] = [
                    'id' => $id,
                    'service' => self::OPERATION_NAMES[$id][0],
                    'name' => self::OPERATION_NAMES[$id][1],
                    'method' => strtoupper($method),
                    'path' => $path,
                    'summary' => $op['summary'] ?? '',
                    'description' => $op['description'] ?? '',
                    'auth' => !(isset($op['security']) && $op['security'] === []),
                    'idempotency_key' => $idempotency,
                    'pathParams' => array_values(array_filter($params, static fn (array $p): bool => $p['in'] === 'path')),
                    'queryParams' => array_values(array_filter($params, static fn (array $p): bool => $p['in'] === 'query')),
                    'body' => isset($op['requestBody']) ? ['required' => ($op['requestBody']['required'] ?? false) === true, 'schema' => $op['requestBody']['content']['application/json']['schema']] : null,
                    'status' => $code,
                    'response' => $listItem === null ? self::refName($responseSchema['$ref']) : null,
                    'listItem' => $listItem,
                ];
            }
        }
        foreach (array_keys(self::OPERATION_NAMES) as $id) {
            if (!in_array($id, array_column($ops, 'id'), true)) {
                throw new RuntimeException("OPERATION_NAMES names $id, which the spec does not have.");
            }
        }

        return $ops;
    }

    /** @param list<array<string, mixed>> $ops */
    private function operationsClass(array $ops): void
    {
        $out = $this->header() . "namespace Hash\\Service;\n\n";
        $out .= "/**\n * Every operation of the API: method, path, whether it takes the API key and an Idempotency-Key,\n * its body, its query parameters and its success status.\n */\n";
        $out .= "final class Operations\n{\n";
        $out .= "    /** @var array<string, array{method: string, path: string, auth: bool, idempotency_key: bool, body: 'none'|'optional'|'required', query: list<string>, status: int, list: bool}> */\n";
        $out .= "    public const ALL = [\n";
        foreach ($ops as $op) {
            $out .= '        ' . var_export($op['id'], true) . " => [\n";
            $out .= "            'method' => " . var_export($op['method'], true) . ",\n";
            $out .= "            'path' => " . var_export($op['path'], true) . ",\n";
            $out .= "            'auth' => " . ($op['auth'] ? 'true' : 'false') . ",\n";
            $out .= "            'idempotency_key' => " . ($op['idempotency_key'] ? 'true' : 'false') . ",\n";
            $out .= "            'body' => " . var_export($op['body'] === null ? 'none' : ($op['body']['required'] ? 'required' : 'optional'), true) . ",\n";
            $out .= "            'query' => [" . implode(', ', array_map(static fn (array $p): string => var_export($p['name'], true), $op['queryParams'])) . "],\n";
            $out .= "            'status' => {$op['status']},\n";
            $out .= "            'list' => " . ($op['listItem'] !== null ? 'true' : 'false') . ",\n";
            $out .= "        ],\n";
        }
        $out .= "    ];\n\n    private function __construct()\n    {\n    }\n}\n";
        $this->files['src/Service/Operations.php'] = $out;
    }

    /**
     * A PHPStan array shape for a request schema.
     *
     * @param array<string, mixed> $schema
     */
    private function shape(array $schema): string
    {
        if (isset($schema['$ref'])) {
            $schema = $this->resolve($schema) + $schema;
            unset($schema['$ref']);
        }
        if (isset($schema['oneOf'])) {
            return implode('|', array_unique(array_map(fn (array $s): string => $this->shape($s), $schema['oneOf'])));
        }
        if (isset($schema['enum'])) {
            return implode('|', array_map(static fn ($v): string => $v === null ? 'null' : var_export($v, true), $schema['enum']));
        }
        $types = is_array($schema['type'] ?? null) ? $schema['type'] : [$schema['type'] ?? 'mixed'];
        $parts = [];
        foreach ($types as $t) {
            $parts[] = match ($t) {
                'string' => 'string',
                'integer' => 'int',
                'number' => 'int|float',
                'boolean' => 'bool',
                'null' => 'null',
                'array' => ($schema['maxItems'] ?? null) === 0 ? 'array{}' : 'list<' . $this->shape($schema['items'] ?? []) . '>',
                'object' => $this->objectShape($schema),
                default => 'mixed',
            };
        }

        return implode('|', $parts);
    }

    /** @param array<string, mixed> $schema */
    private function objectShape(array $schema): string
    {
        if (isset($schema['properties'])) {
            $required = $schema['required'] ?? [];
            $items = [];
            foreach ($schema['properties'] as $name => $p) {
                $items[] = $name . (in_array($name, $required, true) ? '' : '?') . ': ' . $this->shape($p);
            }

            return 'array{' . implode(', ', $items) . '}';
        }
        if (isset($schema['additionalProperties']) && is_array($schema['additionalProperties'])) {
            return 'array<string, ' . $this->shape($schema['additionalProperties']) . '>';
        }

        return 'array<string, mixed>';
    }

    /** @param array<string, mixed> $op */
    private function queryShape(array $op): string
    {
        $flat = [];
        $nested = [];
        foreach ($op['queryParams'] as $p) {
            if (preg_match('/^([a-z_]+)\[([a-z_]+)\]$/', $p['name'], $m) === 1) {
                $nested[$m[1]][] = $m[2] . '?: ' . $this->shape($p['schema']);
            } else {
                $flat[] = $p['name'] . (($p['required'] ?? false) ? '' : '?') . ': ' . $this->shape($p['schema']);
            }
        }
        foreach ($nested as $name => $subs) {
            $flat[] = "$name?: array{" . implode(', ', $subs) . '}';
        }

        return 'array{' . implode(', ', $flat) . '}';
    }

    /** @param list<array<string, mixed>> $ops */
    private function serviceClasses(array $ops): void
    {
        $byService = [];
        foreach ($ops as $op) {
            $byService[$op['service']][] = $op;
        }
        foreach ($byService as $service => $list) {
            $class = self::SERVICE_CLASSES[$service];
            $uses = ['Hash\\ApiRequestor', 'Hash\\Exception\\HashException'];
            $methods = '';
            foreach ($list as $op) {
                $args = [];
                $docParams = [];
                foreach ($op['pathParams'] as $p) {
                    $args[] = 'string $' . $p['name'];
                    $docParams[] = '@param string $' . $p['name'] . ' ' . ($p['description'] ?? '');
                }
                $query = 'null';
                $body = 'null';
                if ($op['queryParams'] !== []) {
                    $args[] = 'array $params = []';
                    $docParams[] = '@param ' . $this->queryShape($op) . ' $params';
                    $query = '$params';
                } elseif ($op['body'] !== null) {
                    $args[] = $op['body']['required'] ? 'array $params' : '?array $params = null';
                    $docParams[] = '@param ' . $this->shape($op['body']['schema']) . ($op['body']['required'] ? '' : '|null') . ' $params';
                    $body = '$params';
                }
                $args[] = 'array $options = []';
                $docParams[] = '@param array{idempotency_key?: string, timeout?: float, max_retries?: int} $options';
                $pathArgs = '[' . implode(', ', array_map(static fn (array $p): string => var_export($p['name'], true) . ' => $' . $p['name'], $op['pathParams'])) . ']';

                if ($op['listItem'] !== null) {
                    $model = $op['listItem'];
                    $uses[] = "Hash\\Model\\$model";
                    $uses[] = 'Hash\\Page';
                    $return = 'Page';
                    $docParams[] = "@return Page<$model>";
                    $bodyCode = "        return \$this->requestor->list(\n            " . var_export($op['id'], true) . ",\n            $pathArgs,\n            $query,\n            \$options,\n            static fn (array \$item): $model => $model::fromArray(\$item),\n        );\n";
                } else {
                    $model = $op['response'];
                    $uses[] = "Hash\\Model\\$model";
                    $return = $model;
                    $bodyCode = "        return $model::fromArray(\$this->requestor->request(" . var_export($op['id'], true) . ", $pathArgs, $query, $body, \$options));\n";
                }
                $docParams[] = '@throws HashException';
                $text = ($op['summary'] !== '' ? $op['summary'] . ".\n\n" : '') . $op['description'] . "\n\n`{$op['method']} {$op['path']}`";
                $methods .= "\n" . self::doc($text, '    ', $docParams);
                $methods .= "    public function {$op['name']}(" . implode(', ', $args) . "): $return\n    {\n$bodyCode    }\n";
            }
            $uses = array_unique($uses);
            sort($uses);
            $out = $this->header() . "namespace Hash\\Service;\n\n";
            foreach ($uses as $u) {
                $out .= "use $u;\n";
            }
            $out .= "\nfinal class $class\n{\n    public function __construct(private readonly ApiRequestor \$requestor)\n    {\n    }\n";
            $out .= $methods . "}\n";
            $this->files["src/Service/$class.php"] = $out;
        }
    }
